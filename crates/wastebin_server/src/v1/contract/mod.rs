//! The generated `/v1` contract.
//!
//! [`document`] assembles the OpenAPI document from the `#[utoipa::path]` annotations of the
//! routed handlers and of [`pending`], adds the shared components and their `$ref`s in
//! [`components::Contract`], and patches at serialisation what utoipa 6.0.0 cannot express
//! (`docs/api/README.md`, "What utoipa 6.0.0 cannot express"). `docs/api/openapi.yaml` is this
//! document; [`tests::document_matches_committed`] fails when the committed file differs.

