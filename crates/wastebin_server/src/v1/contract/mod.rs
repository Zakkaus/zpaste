/// The whole contract as JSON, the form the tests validate against and write as YAML.
pub(crate) fn document() -> Value {
    let mut document = Routed::openapi();
    document.merge(Pending::openapi());
    Contract.modify(&mut document);

    let mut value = serde_json::to_value(&document).expect("serialisable document");
    patch(&mut value);
    value
}

/// The contract as the YAML committed in `docs/api/openapi.yaml`.
pub(crate) fn document_yaml() -> String {
    let yaml = yaml_serde::to_string(&document()).expect("serialisable document");
    format!(
        "# Generated by `cargo test -p wastebin -- --ignored write_openapi_document`.\n\
         # Do not edit; change the handlers in crates/wastebin_server/src/v1 instead.\n{yaml}"
    )
}

/// Serialisation-stage patches for what utoipa's model cannot hold.
fn patch(document: &mut Value) {
    fn headers(value: &mut Value) {
        match value {
            Value::Object(map) => {
                if let Some(Value::Object(headers)) = map.get_mut("headers") {
                    for header in headers.values_mut() {
                        if let Some(object) = header.as_object_mut()
                            && let Some(required) = object.remove("x-required")
                        {
                            object.insert("required".to_owned(), required);
                        }
                    }
                }
                map.values_mut().for_each(headers);
            }
            Value::Array(items) => items.iter_mut().for_each(headers),
            _ => {}
        }
    }

    headers(document);

    // utoipa's `Info` has no `summary` (OpenAPI 3.1).
    document["info"]["summary"] = json!("Paste service API, OpenStack style, under /v1.");

    // `security(())` is the macro's form for "no credentials"; the contract writes `[]`.
    if let Some(Value::Object(paths)) = document.get_mut("paths") {
        for operation in paths.values_mut().filter_map(Value::as_object_mut) {
            for operation in operation.values_mut().filter_map(Value::as_object_mut) {
                if operation.get("security") == Some(&json!([{}])) {
                    operation.insert("security".to_owned(), json!([]));
                }
            }
        }
    }
}

